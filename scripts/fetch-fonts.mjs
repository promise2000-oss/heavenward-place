/**
 * Download the Google webfonts as static variable-font files.
 *
 *   npm run fonts
 *
 * WHY THIS EXISTS
 * ───────────────
 * `next/font/google` fetches font binaries from fonts.gstatic.com at BUILD time.
 * That makes the build depend on reaching Google from whatever machine or CI
 * runner is doing it. When that fetch fails — offline runner, corporate proxy,
 * a poisoned Turbopack font cache — the build dies with an unresolvable
 * `@vercel/turbopack-next/internal/font/google/font` import.
 *
 * A static site should not have a network dependency in its build. This script
 * vendors four variable-font files into `public/fonts/` once, and
 * `src/app/globals.css` declares every family with plain `@font-face`.
 * The build then works anywhere, online or off.
 *
 * The files are committed. Re-run this only to change families or subsets.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** A modern UA is required or Google serves TTF instead of WOFF2. */
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const CSS_URL = 'https://fonts.googleapis.com/css2';

const FAMILIES = [
  {
    name: 'Montserrat',
    /* A range, not a list: one variable file covers every weight. */
    query: 'family=Montserrat:wght@100..900',
    weight: '100 900',
  },
  {
    name: 'Roboto',
    query: 'family=Roboto:wght@100..900',
    weight: '100 900',
  },
];

const SUBSETS = ['latin', 'latin-ext'];

/*
 * The binaries live in `public/fonts/` because they are served as static assets
 * and referenced by URL. The stylesheet that declares them lives in `src/app/`
 * because it is bundled — a bare `/fonts/...` path in an `@import` is not a
 * module specifier, and PostCSS cannot resolve it.
 */
const OUT_DIR = 'public/fonts';
const CSS_OUT = 'src/app/webfonts.css';

function subsetOf(comment) {
  if (comment.includes('latin-ext')) return 'latin-ext';
  if (comment.includes('latin')) return 'latin';
  return null;
}

async function run() {
  mkdirSync(OUT_DIR, { recursive: true });

  const out = [
    '/*',
    ' * Self-hosted webfaces — generated by `npm run fonts`.',
    ' * Do not edit by hand; edit scripts/fetch-fonts.mjs and re-run it.',
    ' *',
    ' * These replace `next/font/google`, which fetched font binaries over the',
    ' * network on every build. A static site must build without a network.',
    ' *',
    ' * Four variable files cover every weight the brand uses.',
    ' *',
    ' * Montserrat and Roboto are licensed under the SIL Open Font License 1.1.',
    ' */',
    '',
  ];

  let total = 0;

  for (const family of FAMILIES) {
    const url = `${CSS_URL}?${family.query}&display=swap`;
    const res = await fetch(url, { headers: { 'user-agent': UA } });
    if (!res.ok) throw new Error(`${family.name}: css ${res.status}`);
    const css = await res.text();

    // Google's CSS labels each block with a `/* latin *\/`-style comment.
    const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g)];

    for (const [, subset, body] of blocks) {
      const name = subsetOf(subset);
      if (!name || !SUBSETS.includes(name)) continue;

      const style = body.match(/font-style:\s*(\w+)/)?.[1] ?? 'normal';
      const stretch = body.match(/font-stretch:\s*([^;]+);/)?.[1]?.trim() ?? 'normal';
      const range = body.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
      const src = body.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
      if (!src) continue;

      const file = `${family.name.toLowerCase()}-${name}.woff2`;

      const fontRes = await fetch(src, { headers: { 'user-agent': UA } });
      if (!fontRes.ok) throw new Error(`${file}: ${fontRes.status}`);

      // Read the body exactly once — a stream can only be consumed once.
      const bytes = Buffer.from(await fontRes.arrayBuffer());
      writeFileSync(join(OUT_DIR, file), bytes);
      total += bytes.length;
      console.log(`  ${file}  ${(bytes.length / 1024).toFixed(1)} kB`);

      out.push(
        '@font-face {',
        `  font-family: '${family.name}';`,
        `  font-style: ${style};`,
        `  font-weight: ${family.weight};`,
        `  font-stretch: ${stretch};`,
        '  font-display: swap;',
        `  src: url('/fonts/${file}') format('woff2');`,
        ...(range ? [`  unicode-range: ${range};`] : []),
        '}',
        '',
      );
    }
  }

  writeFileSync(CSS_OUT, out.join('\n'));
  console.log(`\n${(total / 1024).toFixed(0)} kB total → ${OUT_DIR}`);
}

run().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
